"""Execution modes for Demo Mode AI features.

precomputed - seeded intelligence + rule-based computation over the demo DB (always available)
local       - Ollama, if OLLAMA_URL is set and reachable
cloud       - configurable cloud LLM, if an API key is set

Output from "precomputed" is never presented as newly generated AI analysis.
Model output is validated: every cited evidence ID must exist in the demo DB.
"""
from __future__ import annotations

import json
import re
import time

import httpx

from . import config

EV_ID = re.compile(r"\bEV-\d{4}\b")
MODE_LABELS = {
    "precomputed": "Precomputed demo intelligence (seeded + rule-based; not newly generated by an AI model)",
    "local": "Local AI (Ollama)",
    "cloud": "Cloud AI",
}

# Tests (or embedders) may inject a transport: fn(mode, system, user) -> str
_transport = None
_ping_cache: dict = {"t": 0.0, "ok": False}


def set_transport(fn) -> None:
    global _transport
    _transport = fn


def _ollama_up() -> bool:
    if not config.OLLAMA_URL:
        return False
    if time.time() - _ping_cache["t"] < 15:
        return _ping_cache["ok"]
    try:
        ok = httpx.get(config.OLLAMA_URL.rstrip("/") + "/api/tags", timeout=1.5).status_code == 200
    except Exception:
        ok = False
    _ping_cache.update(t=time.time(), ok=ok)
    return ok


def available_modes() -> dict:
    local = _ollama_up()
    cloud = bool(config.CLOUD_LLM_API_KEY)
    return {"precomputed": True, "local": bool(local), "cloud": cloud}


def describe_modes(requested: str | None = None) -> dict:
    av = available_modes()
    mode = requested if requested in av and av[requested] else "precomputed"
    return {"available": av, "labels": MODE_LABELS, "active": mode,
            "note": None if requested in (None, mode) else f"Requested mode '{requested}' is not configured; using precomputed."}


def resolve_mode(requested: str | None) -> str:
    return describe_modes(requested)["active"]


def chat(mode: str, system: str, user: str) -> str:
    if _transport is not None and mode != "precomputed":
        return _transport(mode, system, user)
    if mode == "local":
        r = httpx.post(config.OLLAMA_URL.rstrip("/") + "/api/chat", timeout=120,
                       json={"model": config.OLLAMA_MODEL, "stream": False,
                             "messages": [{"role": "system", "content": system}, {"role": "user", "content": user}]})
        r.raise_for_status()
        return r.json()["message"]["content"]
    if mode == "cloud":
        if config.CLOUD_LLM_PROVIDER == "openai":
            base = (config.CLOUD_LLM_BASE_URL or "https://api.openai.com/v1").rstrip("/")
            r = httpx.post(base + "/chat/completions", timeout=120,
                           headers={"Authorization": f"Bearer {config.CLOUD_LLM_API_KEY}"},
                           json={"model": config.CLOUD_LLM_MODEL or "gpt-4o-mini",
                                 "messages": [{"role": "system", "content": system}, {"role": "user", "content": user}]})
            r.raise_for_status()
            return r.json()["choices"][0]["message"]["content"]
        r = httpx.post((config.CLOUD_LLM_BASE_URL or "https://api.anthropic.com").rstrip("/") + "/v1/messages", timeout=120,
                       headers={"x-api-key": config.CLOUD_LLM_API_KEY, "anthropic-version": "2023-06-01"},
                       json={"model": config.CLOUD_LLM_MODEL or "claude-sonnet-5-5", "max_tokens": 3000,
                             "system": system, "messages": [{"role": "user", "content": user}]})
        r.raise_for_status()
        return r.json()["content"][0]["text"]
    raise ValueError("chat() is not used for precomputed mode")


def cited_ids(text: str) -> list[str]:
    seen, out = set(), []
    for m in EV_ID.findall(text):
        if m not in seen:
            seen.add(m)
            out.append(m)
    return out


def validate_ids(ids, known: set[str]) -> tuple[list[str], list[str]]:
    ids = list(ids)
    return [i for i in ids if i in known], [i for i in ids if i not in known]


def extract_json(text: str):
    text = text.strip()
    fence = re.search(r"```(?:json)?\s*(.*?)```", text, re.S)
    if fence:
        text = fence.group(1)
    start, end = text.find("{"), text.rfind("}")
    return json.loads(text[start:end + 1])


